// JoinNodes join K3S nodes.
// nolint: gocyclo
func (p *ProviderBase) JoinNodes(cloudInstanceFunc func(ssh *types.SSH) (*types.Cluster, error),
	syncExistInstance func() error, isAutoJoined bool, rollbackInstance func(ids []string) error,
	generateMasterExtraArgs, generateWorkerExtraArgs func(*types.Cluster, types.Node) string) (er error) {
	if p.M == nil {
		p.M = new(syncmap.Map)
	}
	logFile, err := common.GetLogFile(p.ContextName)
	if err != nil {
		return err
	}
	state, err := common.DefaultDB.GetCluster(p.Name, p.Provider)
	if err != nil {
		return err
	}
	if state == nil {
		return fmt.Errorf("[%s] cluster %s is not exist", p.Provider, p.Name)
	}
	defer func() {
		if er != nil || len(p.ErrM) > 0 {
			// join failed.
			state, err = common.DefaultDB.GetCluster(p.Name, p.Provider)
			if err == nil {
				if len(p.ErrM) > 0 {
					// remove failed node from cluster state
					workerNodes := []types.Node{}
					_ = json.Unmarshal(state.WorkerNodes, &workerNodes)
					workers := []types.Node{}
					for _, n := range workerNodes {
						if _, ok := p.ErrM[n.InstanceID]; !ok {
							workers = append(workers, n)
						}
					}
					wb, err := json.Marshal(workers)
					if err == nil {
						state.WorkerNodes = wb
					}
					state.Worker = strconv.Itoa(len(workers))
				}
				state.Status = common.StatusRunning
				_ = common.DefaultDB.SaveClusterState(state)
				// rollback instance.
				_ = p.RollbackCluster(rollbackInstance)
			}
		}
		// remove join state file and save running state.
		_ = logFile.Close()
		if p.Callbacks != nil {
			if process, ok := p.Callbacks[p.ContextName]; ok && process.Event == "update" {
				logEvent := &common.LogEvent{
					Name:        process.Event,
					ContextType: "cluster",
					ContextName: p.ContextName,
				}
				process.Fn(logEvent)
			}
		}
	}()

	p.Logger = common.NewLogger(logFile)
	p.Logger.Infof("[%s] begin to join nodes for %v...", p.Provider, p.Name)
	state.Status = common.StatusUpgrading
	err = common.DefaultDB.SaveClusterState(state)
	if err != nil {
		return err
	}

	c, err := cloudInstanceFunc(&state.SSH)
	if err != nil {
		p.Logger.Errorf("[%s] failed to prepare instance, got error %v", p.Provider, err)
		return err
	}

	if syncExistInstance != nil {
		err = syncExistInstance()
		if err != nil {
			return err
		}
	}

	p.syncExistNodes()
	c.Status.MasterNodes = p.Status.MasterNodes
	c.Status.WorkerNodes = p.Status.WorkerNodes

	added := &types.Cluster{
		Metadata: c.Metadata,
		Options:  c.Options,
		Status:   types.Status{},
	}

	p.M.Range(func(key, value interface{}) bool {
		v := value.(types.Node)
		// filter the number of nodes that are not generated by current command.
		if v.Current && v.Master {
			added.Status.MasterNodes = append(added.Status.MasterNodes, v)
		} else if v.Current && !v.Master {
			added.Status.WorkerNodes = append(added.Status.WorkerNodes, v)
		}
		return true
	})

	if !isAutoJoined {
		// execute k3s script to join nodes.
		err = p.Join(c, added, generateMasterExtraArgs, generateWorkerExtraArgs)
	} else {
		// some providers do not need to execute the K3s join logic,
		// so we need to fill in the missing key information.
		prevMasterNum, _ := strconv.Atoi(state.Master)
		prevWorkerNum, _ := strconv.Atoi(state.Worker)
		addedMasterNum, _ := strconv.Atoi(added.Master)
		addedWorkerNum, _ := strconv.Atoi(added.Worker)
		c.Master = strconv.Itoa(prevMasterNum + addedMasterNum)
		c.Worker = strconv.Itoa(prevWorkerNum + addedWorkerNum)
		c.Status.Status = common.StatusRunning
		err = common.DefaultDB.SaveCluster(c)
	}

	p.Logger.Infof("[%s] successfully executed join logic", p.Provider)
	return err
}

// Join join K3S nodes to exist K3S cluster.
func (p *ProviderBase) Join(merged, added *types.Cluster,
	generateMasterExtraArgs, generateWorkerExtraArgs func(*types.Cluster, types.Node) string) error {
	p.Logger.Infof("[%s] executing join k3s node logic", merged.Provider)

	pkg, err := airgap.PreparePackage(merged)
	if err != nil {
		return err
	}
	// package's name is empty, it means that it is a temporary dir and it needs to be remove after.
	if pkg != nil && pkg.Name == "" {
		defer os.RemoveAll(pkg.FilePath)
	}

	if merged.IP == "" {
		if len(merged.MasterNodes) <= 0 || len(merged.MasterNodes[0].InternalIPAddress) <= 0 {
			return errors.New("[cluster] master node internal ip address can not be empty")
		}
		merged.IP = merged.MasterNodes[0].InternalIPAddress[0]
	}
	publicIP := merged.IP

	// get cluster token from `--ip` address.
	if merged.Token == "" {
		serverNode := types.Node{}
		if len(added.MasterNodes) > 0 {
			serverNode = added.MasterNodes[0]
		} else {
			serverNode = added.WorkerNodes[0]
		}
		serverNode.PublicIPAddress = []string{merged.IP}
		token, err := p.execute(&serverNode, k3s.TokenCommand)
		if err != nil {
			return err
		}
		merged.Token = strings.TrimSpace(token)
	}

	if merged.Token == "" {
		return errors.New("[cluster] k3s token can not be empty")
	}

	masterNodes := nodeByInstanceID(merged.MasterNodes)
	workerNodes := nodeByInstanceID(merged.WorkerNodes)

	for i := 0; i < len(added.Status.MasterNodes); i++ {
		currentNode := added.MasterNodes[i]
		full, ok := masterNodes[currentNode.InstanceID]
		if !ok {
			continue
		}
		extraArgs := merged.MasterExtraArgs
		p.Logger.Infof("[%s] joining k3s master-%d...", merged.Provider, i+1)
		additionalExtraArgs := generateMasterExtraArgs(added, full)
		if additionalExtraArgs != "" {
			extraArgs += additionalExtraArgs
		}
		if err := p.initNode(false, publicIP, merged, full, extraArgs, pkg); err != nil {
			return err
		}
		p.Logger.Infof("[%s] successfully joined k3s master-%d", merged.Provider, i+1)
	}

	var wg sync.WaitGroup
	var l sync.RWMutex

	for i := 0; i < len(added.Status.WorkerNodes); i++ {
		currentNode := added.WorkerNodes[i]
		full, ok := workerNodes[currentNode.InstanceID]
		if !ok {
			continue
		}
		wg.Add(1)

		go func(i int, node types.Node) {
			defer wg.Done()
			p.Logger.Infof("[%s] joining k3s worker-%d...", merged.Provider, i+1)
			extraArgs := merged.WorkerExtraArgs
			additionalExtraArgs := generateWorkerExtraArgs(added, full)
			if additionalExtraArgs != "" {
				extraArgs += additionalExtraArgs
			}
			if err := p.initNode(false, publicIP, merged, full, extraArgs, pkg); err != nil {
				l.Lock()
				p.ErrM[full.InstanceID] = err.Error()
				l.Unlock()
			}
			p.Logger.Infof("[%s] successfully joined k3s worker-%d", merged.Provider, i+1)
		}(i, full)
	}
	wg.Wait()

	// sync master & worker numbers.
	merged.Master = strconv.Itoa(len(merged.MasterNodes))
	merged.Worker = strconv.Itoa(len(merged.WorkerNodes))

	if p.Provider == "native" {
		// check cluster context exists
		kubeCfg := filepath.Join(common.CfgPath, common.KubeCfgFile)
		clientConfig, err := clientcmd.LoadFromFile(kubeCfg)
		if err != nil {
			return err
		}
		contexts := clientConfig.Contexts
		if _, ok := contexts[p.ContextName]; !ok {
			// get k3s cluster config.
			cfg, err := p.execute(&types.Node{
				PublicIPAddress: []string{merged.IP},
				SSH:             merged.SSH,
				Master:          true,
			}, k3s.CatConfigCommand)
			if err == nil {
				// merge current cluster to kube config.
				if err := kube.SaveConfig(cfg, merged.IP, p.ContextName); err != nil {
					p.Logger.Warnf("[%s] can't save kubeconfig file with error: %v", merged.Provider, err)
				}
				_ = os.Setenv(clientcmd.RecommendedConfigPathEnvVar, filepath.Join(common.CfgPath, common.KubeCfgFile))
			} else {
				p.Logger.Warnf("[%s] can't get kubeconfig file from master %s", merged.Provider, merged.IP)
			}
		}
	}

	merged.Status.Status = common.StatusRunning
	// write current cluster to state file.
	if err = common.DefaultDB.SaveCluster(merged); err != nil {
		p.Logger.Errorf("failed to save cluster state: %v", err)
		return nil
	}

	p.Logger.Infof("[%s] successfully executed join k3s node logic", merged.Provider)
	return nil
}

func nodeByInstanceID(nodes []types.Node) map[string]types.Node {
	rtn := make(map[string]types.Node, len(nodes))
	for _, node := range nodes {
		rtn[node.InstanceID] = node
	}
	return rtn
}
